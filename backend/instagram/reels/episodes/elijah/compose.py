"""엘리야 릴스 v5 음악(58초, 도망 짧게·끝 길게). 장면: 도입·불(0–11) · 위협(11–16.6) · 도망(16.6–23) · 광야(23–28) · 잠과 빵(28–43.6) · 먹음(43.6–48) · 걷기(48–57)."""
OFF = [0.0]
import json, sys
ev = []
def note(t, dur, n, vel, inst='piano'):
    t = t + OFF[0]
    ev.append({'t': round(t, 3), 'dur': round(dur, 3), 'note': n, 'vel': vel, 'inst': inst})
def block(t0, dur, bass, arp, step, vb, va, pad=None, vp=0, ring=0.5):
    for b in bass: note(t0, dur + 0.4, b, vb)
    k, t = 0, t0
    while t < t0 + dur - 1e-6:
        note(t, (t0 + dur) - t + ring, arp[k % len(arp)], va); t += step; k += 1
    for p in (pad or []): note(t0, dur + 0.3, p, vp, 'strings')
def melody(items, vel):
    for t, d, n in items: note(t, d + 0.3, n, vel)
def pulse(t0, t1, n, vel_from, vel_to, step=0.6):
    t = t0
    while t < t1 - 1e-6:
        v = int(vel_from + (vel_to - vel_from) * (t - t0) / max(0.01, t1 - t0))
        note(t, 0.5, n, v); note(t, 0.5, n + 12, max(20, v - 12)); t += step

# A 도입 (0–3.2): 조용한 D단조 화음, 높은 현악이 떠 있음 — "가장 용감한 사람도 벽에 부딪힌다"
for n in [38, 50, 57, 62]: note(0.0, 3.4, n, 40)
for n in [69, 74]: note(0.0, 3.3, n, 34, 'strings')
melody([(1.0, 1.0, 69), (2.0, 1.0, 65)], 44)
# B 엘리야와 갈멜산 (3.2–11): Bb–C–F 로 차오르고, "하늘에서 불"에서 가장 크게
block(3.2, 1.8, [34, 46], [53, 58, 62, 65], 0.45, 46, 36, [53, 58, 62], 40)
block(5.0, 1.6, [36, 48], [55, 60, 64, 67], 0.4, 50, 38, [55, 60, 64], 44)
block(6.6, 2.0, [41, 53], [57, 60, 65, 69], 0.4, 54, 40, [57, 60, 65], 48)
melody([(3.4, 0.8, 70), (4.2, 0.8, 74), (5.0, 0.8, 72), (5.8, 0.8, 76), (6.6, 1.0, 77), (7.6, 1.0, 81)], 56)
for n in [29, 41, 53, 57, 60, 65, 69]: note(8.6, 2.6, n, 66)
for n in [57, 60, 65, 69, 72]: note(8.6, 2.5, n, 58, 'strings')
melody([(8.6, 0.6, 77), (9.2, 0.6, 81), (9.8, 1.2, 84)], 64)
# C 이세벨 (11–17): 갑자기 꺼지고 낮은 심장 박동 + 반음 부딪힘
t = 11.0
while t < 16.6 - 1e-6:
    note(t, 0.55, 38, 50); t += 0.75
note(11.0, 3.0, 46, 46, 'strings'); note(14.0, 2.8, 45, 46, 'strings')
for n in [50, 53, 58]: note(11.0, 3.0, n, 36)
for n in [50, 52, 57]: note(14.0, 2.7, n, 36)

# C2 도망 (16.6–20.4): 박동이 빨라지며 쫓기듯, 19.4 부터 잦아들어 광야로 넘어간다
t, step = 16.6, 0.45
while t < 19.4 - 1e-6:
    note(t, step * 0.8, 38, 54); note(t, step * 0.8, 50, 40); t += step; step = max(0.28, step - 0.025)
for t0, d, n in [(16.6, 1.0, 50), (17.6, 1.0, 51), (18.6, 0.9, 52)]:
    note(t0, d + 0.1, n, 50, 'strings'); note(t0, d + 0.1, n + 3, 46, 'strings')
melody([(16.9, 0.4, 74), (17.3, 0.4, 72), (17.7, 0.6, 69), (18.4, 0.4, 72), (18.8, 0.6, 70)], 52)
for t0, v in [(19.4, 44), (19.9, 36)]: note(t0, 0.6, 38, v)
note(19.4, 1.2, 45, 32, 'strings'); melody([(19.5, 0.9, 65)], 40)
OFF[0] = 3.4  # 이 아래(광야부터)는 v3 보다 3.4초 뒤
# D 광야 (17–22 → 23–28): 성긴 피아노, 한숨, "It is enough"에서 풀리지 않는 화음
block(17.0, 2.5, [31, 38], [43, 50, 58, 50], 1.0, 44, 34)
