ev = []


def note(t, dur, n, vel, inst='piano'):
    ev.append({'t': round(t, 3), 'dur': round(dur, 3), 'note': n, 'vel': vel, 'inst': inst})


def block(t0, dur, bass, arp, step, vb, va, pad=None, vp=0, ring=0.5):
    for b in bass:
        note(t0, dur + 0.4, b, vb)
    k, t = 0, t0
    while t < t0 + dur - 1e-6:
        note(t, (t0 + dur) - t + ring, arp[k % len(arp)], va)
        t += step
        k += 1
    for p in (pad or []):
        note(t0, dur + 0.3, p, vp, 'strings')


def melody(items, vel):
    for t, d, n in items:
        note(t, d + 0.3, n, vel)


def ping(t, n, vel=40):  # 번호·동그라미 — 높은 음 하나(옥타브 아래를 살짝 겹쳐 둥글게)
    note(t, 1.4, n, vel)
    note(t, 1.2, n - 12, vel - 14)


def walk(t0, dur, notes, vel, step=0.3):  # 조사하듯 걷는 8분음(짧게 끊어)
    k, t = 0, t0
    while t < t0 + dur - 1e-6:
        note(t, step * 0.8, notes[k % len(notes)], vel)
        t += step
        k += 1


