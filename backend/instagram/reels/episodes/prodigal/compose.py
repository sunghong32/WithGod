ev = []


def note(t, dur, n, vel, inst='piano'):
    ev.append({'t': round(t, 3), 'dur': round(dur, 3), 'note': n, 'vel': vel, 'inst': inst})


def block(t0, dur, bass, arp, step, vb, va, pad=None, vp=0, ring=0.5):
    for b in bass:
        note(t0, dur + 0.4, b, vb)
    k, t = 0, t0
    while t < t0 + dur - 1e-6:
        note(t, (t0 + dur) - t + ring, arp[k % len(arp)], va)
        t += step
        k += 1
    for p in (pad or []):
        note(t0, dur + 0.3, p, vp, 'strings')


def melody(items, vel):
    for t, d, n in items:
        note(t, d + 0.3, n, vel)


