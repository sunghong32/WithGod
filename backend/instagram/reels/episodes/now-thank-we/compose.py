def note(t, dur, n, vel, inst):
    ev.append({'t': round(t, 3), 'dur': round(dur, 3), 'note': n, 'vel': max(1, min(127, int(vel))), 'inst': inst})


def at(voice, line, pos):
    """그 줄 pos(4분음)에 울리는 음."""
    for p, d, n in voice[line]:
        if p <= pos < p + d:
            return n
    return voice[line][-1][2]


def part(t0, voice, line, vel, inst, shift=0, last=False, legato=1.03, accent=True):
    for p, d, n in voice[line]:
        dur = LAST_HOLD if last and p + d >= 8 else d * Q * legato
        v = vel + (4 if accent and p in (1.0, 5.0) else 0)  # 마디 첫 박만 살짝
        note(t0 + p * Q, dur, n + shift, v, inst)


def held_bass(t0, line, vel, inst, shift=0):
    """마디마다 그 자리 베이스 음을 길게(못갖춘 0박 1박 · 1박부터 4박 · 5박부터 3박) — 독주 밑에 조용히 깔 때."""
    for p, length in ((0.0, 1.0), (1.0, 4.0), (5.0, 3.0)):
        note(t0 + p * Q, length * Q + 0.05, at(B, line, p) + shift, vel, inst)


def sus_chords(t0, line, vel, last=False):
    """역병: 선율을 빼고, 마디마다(줄 안 1·5박, 못갖춘 0박) 그 자리 베이스 위에 5도 + 2도(3음 없는 sus2) — 풀리지 않게, 박 위에만.
    같은 화음이 이어지면 다시 치지 않고 길게 둔다(현악은 다시 칠 때마다 느린 어택부터 시작해 B1 이 거의 안 들렸다)."""
    segs = []
    for p, length in ((0.0, 1.0), (1.0, 4.0), (5.0, 3.0)):
        b = at(B, line, p)
        while b > 54:  # 베이스를 G2~F#3 에 모아 무겁지만 들리게
            b -= 12
        while b < 43:
            b += 12
        if segs and segs[-1][2] == b:
            segs[-1][1] += length
        else:
            segs.append([p, length, b])
        if p in (1.0, 5.0):  # 조종 — 마디 첫 박에 아주 작게, 그 마디 베이스 음
            note(t0 + p * Q, 2.6, b + 12, vel - 14, 'gm14')
    for p, length, b in segs:
        dur = length * Q + 0.05
        note(t0 + p * Q, dur, b, vel + 4, 'gm48')
        note(t0 + p * Q, dur, b - 12, vel, 'gm19')
        for x in (b + 7, b + 14):
            note(t0 + p * Q + 0.02, dur, x, vel - 6, 'gm48')


def guitar(t0, line, vel, last=False):
    """나일론 기타(류트처럼) — 8분음마다 한 음: 베이스 · 테너 · 알토 · 테너(바흐 성부에서 그 자리의 음, 박 위에만 고르게)."""
    order = (B, T, A, T)
    for k in range(16):
        pos = k * 0.5
        if last and pos >= 5.0:
            if pos == 5.0:
                for i, v in enumerate((B, T, A)):
                    note(t0 + pos * Q + 0.05 * i, LAST_HOLD, at(v, line, pos) - (12 if v is B and at(v, line, pos) > 52 else 0), vel, 'gm24')
            continue
        v = order[k % 4]
        n = at(v, line, pos)
        if v is B and n > 52:
            n -= 12
        note(t0 + pos * Q, Q * 1.2, n, vel + (6 if k % 4 == 0 else 0), 'gm24')


